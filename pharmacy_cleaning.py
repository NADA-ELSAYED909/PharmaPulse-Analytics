import pandas as pd
import numpy as np
import re
from pathlib import Path

# ============================================================
# Settings: put all raw files in one folder and change this path
# ============================================================
RAW = Path("/content")   # Colab upload folder (on your PC use e.g. Path(r"C:\Users\...\Downloads"))
OUT = Path("/content")   # cleaned files are saved here

def find(prefix):
    """Find the file that starts with this name, so (3) or _5_ in the name doesn't matter."""
    files = sorted(RAW.glob(prefix + "*.csv"))
    if not files:
        raise FileNotFoundError(f"No file starting with '{prefix}' in {RAW}")
    return files[0]

# ============================================================
# 1. LOAD: Sales comes in 3 files with different column names
#    and different date formats, so we unify then stack them
# ============================================================
g1 = pd.read_csv(find("sales_group1"))
g2 = pd.read_csv(find("sales_group2")).rename(columns={"qty": "quantity", "amount": "unit_price"})
g3 = pd.read_csv(find("sales_group3"))
sales = pd.concat([g1, g2, g3], ignore_index=True)

products = pd.read_csv(find("products_catalog"))
customers = pd.read_csv(find("customers_master"))

print("Sales rows before cleaning:", len(sales))

# ============================================================
# 2. CLEAN SALES
# ============================================================
# 2.1 Remove exact duplicate rows
before = len(sales)
sales = sales.drop_duplicates().reset_index(drop=True)
print("Duplicate rows removed:", before - len(sales))

# 2.2 Price: remove "$" and any text, convert to number
sales["unit_price"] = (sales["unit_price"].astype(str)
                       .str.replace(r"[^\d.]", "", regex=True).astype(float))

# 2.3 Dates: the files use TWO formats (15/03/2025 and 2025-03-15).
#     We parse each format separately, so no date is lost.
d = sales["sale_date"].astype(str).str.strip()
is_slash = d.str.match(r"^\d{2}/\d{2}/\d{4}$")
parsed = pd.Series(pd.NaT, index=sales.index, dtype="datetime64[ns]")
parsed[is_slash]  = pd.to_datetime(d[is_slash],  format="%d/%m/%Y", errors="coerce")
parsed[~is_slash] = pd.to_datetime(d[~is_slash], format="%Y-%m-%d", errors="coerce")
sales["sale_date"] = parsed
print("Dates that failed to convert:", sales["sale_date"].isna().sum())

# 2.4 Payment method: unify the text (cash / CASH -> Cash), keep real nulls
sales["payment_method"] = sales["payment_method"].str.strip().str.title()

# 2.5 Notes -> promo code + discount reason
def extract_promo(note):
    if pd.isna(note) or note == "":
        return pd.Series({"promo_code": None, "discount_reason": None})
    note = str(note)
    m = re.search(r"Promo code (\w+) applied at checkout", note, re.IGNORECASE)
    if m:
        return pd.Series({"promo_code": m.group(1), "discount_reason": "promo code"})
    if "competitor" in note.lower():
        return pd.Series({"promo_code": None, "discount_reason": "price_match"})
    if "loyalty" in note.lower():
        return pd.Series({"promo_code": None, "discount_reason": "loyalty_tier"})
    return pd.Series({"promo_code": None, "discount_reason": "other"})

sales = pd.concat([sales, sales["notes"].apply(extract_promo)], axis=1)

# ============================================================
# 3. PRODUCTS
# ============================================================
def parse_pack_info(val):
    if pd.isna(val) or val == "":
        return pd.Series({"pack_size": None, "strength": None, "form": None})
    v = str(val)
    g = lambda p: (re.search(p, v, re.IGNORECASE).group(1).strip()
                   if re.search(p, v, re.IGNORECASE) else None)
    return pd.Series({"pack_size": g(r"Pack:\s*([^|/]+)"),
                      "strength":  g(r"Strength:\s*([^|/]+)"),
                      "form":      g(r"Form:\s*([^|/]+)")})

products = pd.concat([products, products["pack_info"].apply(parse_pack_info)], axis=1)

# ============================================================
# 4. FINANCIAL METRICS (cost comes from the products table)
# ============================================================
assert products["product_id"].is_unique, "Duplicate product_id: merge would duplicate sales rows"
sales = sales.merge(products[["product_id", "cost_price"]], on="product_id", how="left")

sales["total_amount"] = (sales["quantity"] * sales["unit_price"] * (1 - sales["discount_pct"] / 100)).round(2)
sales["cost_amount"]  = (sales["quantity"] * sales["cost_price"]).round(2)
sales["profit"]       = (sales["total_amount"] - sales["cost_amount"]).round(2)
sales["margin_pct"]   = np.where(sales["total_amount"] != 0,
                                 (sales["profit"] / sales["total_amount"] * 100).round(2), 0.0)

# ============================================================
# 5. NEW ANALYSIS COLUMNS
# ============================================================
sales["is_loss"] = (sales["profit"] < 0).astype(int)
sales["discount_band"] = pd.cut(sales["discount_pct"],
                                bins=[-0.01, 5, 10, 15, np.inf],
                                labels=["0-5%", "5-10%", "10-15%", "15%+"])
sales["sale_month"] = sales["sale_date"].dt.to_period("M").dt.to_timestamp()

# ============================================================
# 6. CUSTOMERS
# ============================================================
def extract_loyalty(note):
    if pd.isna(note) or note == "":
        return pd.Series({"loyalty_tier": None, "loyalty_since": None})
    m = re.search(r"(Silver|Gold|Platinum)\s+member\s*-\s*loyalty\s+since\s+(\d{4})", str(note), re.IGNORECASE)
    if m:
        return pd.Series({"loyalty_tier": m.group(1).capitalize(), "loyalty_since": int(m.group(2))})
    return pd.Series({"loyalty_tier": None, "loyalty_since": None})

customers = pd.concat([customers, customers["notes"].apply(extract_loyalty)], axis=1)
customers["phone_clean"] = customers["phone"].astype(str).str.replace(r"\D", "", regex=True)
customers["city_clean"]  = customers["city"].astype(str).str.strip().str.title()

# Same person entered twice with a typo in the name (Andrew / Anddrew) -> same phone.
# Keep the lowest customer_id. Rows with an empty phone are NEVER treated as duplicates.
customers = customers.sort_values(["phone_clean", "customer_id"])
has_phone = customers["phone_clean"].str.len() > 0
dup = has_phone & customers.duplicated(subset=["phone_clean"], keep="first")
print("Duplicate customers removed:", dup.sum())
customers_clean = customers[~dup].reset_index(drop=True)

# ============================================================
# 7. QUALITY CHECKS (print them, and explain them in the interview)
# ============================================================
orphans = (~sales["customer_id"].isin(customers_clean["customer_id"])).sum()
print("Sales with a customer_id missing from Customers:", orphans)
print("Sales with missing cost_price:", sales["cost_price"].isna().sum())
print("Loss sales:", sales["is_loss"].sum(), f"({sales['is_loss'].mean()*100:.2f}%)")
print("Total revenue:", round(sales["total_amount"].sum(), 2), "| Total profit:", round(sales["profit"].sum(), 2))

# ============================================================
# 8. EXPORT (dates saved as YYYY-MM-DD so SQL and Power BI read them correctly)
# ============================================================
sales.to_csv(OUT / "sales_cleaned.csv", index=False, date_format="%Y-%m-%d")
products.to_csv(OUT / "products_cleaned.csv", index=False)
customers_clean.to_csv(OUT / "customers_cleaned.csv", index=False)